"""Small repository ports shared by persistence adapters, independent of HTTP."""

from collections.abc import Callable, Iterator
from typing import Any, Protocol, TypeVar

from ..catalogue_query import MovieQuery
from ..circulation_model import CirculationQuery
from ..personal_model import PersonalQuery

type Record = dict[str, Any]
T = TypeVar("T")


class ReadAccounts(Protocol):
    def by_ids(self, identities: list[str]) -> list[Record]: ...
    def get(self, identity: str) -> Record | None: ...
    def by_username(self, username: str) -> Record | None: ...
    def page(self, limit: int, offset: int) -> list[Record]: ...
    def has_other_enabled_admin(self, identity: str) -> bool: ...


class Accounts(ReadAccounts, Protocol):
    def insert(self, account: Record) -> None: ...
    def save(self, account: Record) -> None: ...


class ReadSessions(Protocol):
    def by_token_hash(self, token_hash: str) -> Record | None: ...


class Sessions(ReadSessions, Protocol):
    def touch(self, identity: str, timestamp: int) -> None: ...
    def insert(self, session: Record) -> None: ...
    def revoke_user(self, user_id: str) -> int: ...
    def revoke(self, identity: str) -> bool: ...
    def delete_expired(self, timestamp: int, *, idle_ttl: int) -> int: ...


class ReadAttempts(Protocol):
    def get_many(self, keys: list[str]) -> dict[str, Record]: ...
    def count(self) -> int: ...


class Attempts(ReadAttempts, Protocol):
    def prune_expired(self, timestamp: int, *, window: int) -> int: ...
    def set(self, attempt: Record) -> None: ...


class ReadReceipts(Protocol):
    def get(self, actor_id: str, key_hash: str) -> Record | None: ...
    def count(self) -> int: ...


class Receipts(ReadReceipts, Protocol):
    def prune_expired(self, timestamp: int) -> int: ...
    def insert(self, receipt: Record) -> None: ...


class ReadCatalogue(Protocol):
    def movie(self, identity: str) -> Record | None: ...
    def movies_by_ids(self, identities: list[str]) -> list[Record]: ...
    def copy(self, identity: str) -> Record | None: ...
    def copies_for_movie(self, movie_id: str) -> list[Record]: ...
    def copies(self, movie_id: str | None = None) -> list[Record]: ...
    def search_movies(self, query: MovieQuery) -> tuple[list[Record], int]: ...
    def copy_summaries(self, movie_ids: list[str]) -> dict[str, Record]: ...
    def has_duplicate_movie(self, movie: Record, *, excluded_id: str | None = None) -> bool: ...
    def has_movie_references(self, movie_id: str) -> bool: ...
    def has_copy_history(self, copy_id: str) -> bool: ...


class Catalogue(ReadCatalogue, Protocol):
    def insert_movie(self, movie: Record) -> None: ...
    def save_movie(self, movie: Record) -> None: ...
    def delete_movie(self, identity: str) -> bool: ...
    def insert_copy(self, copy: Record) -> None: ...
    def save_copy(self, copy: Record) -> None: ...
    def delete_copy(self, identity: str) -> bool: ...


class ReadPersonal(Protocol):
    def get_owned(self, owner_id: str, identity: str) -> Record | None: ...
    def page(self, owner_id: str, query: PersonalQuery) -> tuple[list[Record], int]: ...
    def has_duplicate(self, entry: Record, *, excluded_id: str | None = None) -> bool: ...


class Personal(ReadPersonal, Protocol):
    def insert(self, entry: Record) -> None: ...
    def save_owned(self, owner_id: str, entry: Record) -> None: ...
    def delete_owned(self, owner_id: str, identity: str) -> bool: ...


class ReadEvents(Protocol):
    def page(self, limit: int, offset: int) -> tuple[list[Record], int]: ...


class Events(ReadEvents, Protocol):
    def append(self, event: Record) -> None: ...


class ReadCirculation(Protocol):
    def loan(self, identity: str, *, owner_id: str | None = None) -> Record | None: ...
    def reservation(self, identity: str, *, owner_id: str | None = None) -> Record | None: ...
    def loans_page(
        self, owner_id: str | None, query: CirculationQuery
    ) -> tuple[list[Record], int]: ...
    def reservations_page(
        self, owner_id: str | None, query: CirculationQuery
    ) -> tuple[list[Record], int]: ...
    def open_loan(self, borrower_id: str, movie_id: str) -> Record | None: ...
    def count_loans(self, borrower_id: str, status: str) -> int: ...
    def active_for_copy(self, copy_id: str) -> bool: ...
    def count_waiting_for_user(self, user_id: str) -> int: ...
    def queue_facts(
        self,
        movie_id: str,
        timestamp: int,
        *,
        user_id: str | None = None,
        before_sequence: int | None = None,
    ) -> Record: ...
    def open_loans_for_pairs(self, pairs: list[tuple[str, str]]) -> list[Record]: ...
    def inventory_counts(self, movie_id: str) -> Record: ...
    def free_copies(self, movie_id: str) -> list[Record]: ...
    def expired_batches(self, timestamp: int, batch_size: int = 500) -> Iterator[list[Record]]: ...
    def waiting_user_batches(
        self, user_id: str, batch_size: int = 500
    ) -> Iterator[list[Record]]: ...


class Circulation(ReadCirculation, Protocol):
    def insert_loan(self, loan: Record) -> None: ...
    def save_loan(self, loan: Record, *, owner_id: str | None = None) -> None: ...
    def insert_reservation(self, reservation: Record) -> None: ...
    def save_reservation(self, reservation: Record, *, owner_id: str | None = None) -> None: ...


class ReadWork(Protocol):
    @property
    def circulation(self) -> ReadCirculation: ...

    @property
    def personal(self) -> ReadPersonal: ...

    @property
    def events(self) -> ReadEvents: ...
    @property
    def revision(self) -> int: ...

    @property
    def accounts(self) -> ReadAccounts: ...

    @property
    def sessions(self) -> ReadSessions: ...

    @property
    def attempts(self) -> ReadAttempts: ...

    @property
    def receipts(self) -> ReadReceipts: ...

    @property
    def catalogue(self) -> ReadCatalogue: ...


class Work(ReadWork, Protocol):
    @property
    def circulation(self) -> Circulation: ...

    @property
    def personal(self) -> Personal: ...

    @property
    def events(self) -> Events: ...
    @property
    def accounts(self) -> Accounts: ...

    @property
    def sessions(self) -> Sessions: ...

    @property
    def attempts(self) -> Attempts: ...

    @property
    def receipts(self) -> Receipts: ...

    @property
    def catalogue(self) -> Catalogue: ...


class Persistence(Protocol):
    def run(self, command: Callable[[Work], T]) -> T: ...
    def query(self, query: Callable[[ReadWork], T]) -> T: ...
    def readiness(self) -> None: ...
